#!/usr/bin/env node
/**
 * Posts every test input to /api/extract and writes docs/failure-case-evidence.md.
 * The backend must be running with --sakhi.llm.fail=true so every request
 * exercises the offline fallback path (that is the failure case under test).
 *
 * Usage: node scripts/generate-evidence.mjs <apiBase> <inputsJson> <outputMd>
 * Exits non-zero if any request fails.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const [apiBase, inputsPath, outputPath] = process.argv.slice(2);
if (!apiBase || !inputsPath || !outputPath) {
  console.error('usage: generate-evidence.mjs <apiBase> <inputsJson> <outputMd>');
  process.exit(2);
}

const inputs = JSON.parse(readFileSync(resolve(inputsPath), 'utf8'));
if (inputs.length !== 20) {
  console.error(`expected 20 test inputs, found ${inputs.length}`);
  process.exit(1);
}

function esc(value) {
  return String(value ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

const rows = [];
let failures = 0;

for (const input of inputs) {
  let response;
  try {
    response = await fetch(`${apiBase}/api/extract`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text: input.text }),
    });
  } catch (err) {
    failures += 1;
    rows.push({ input, error: `request failed: ${err.message}` });
    continue;
  }
  if (!response.ok) {
    failures += 1;
    rows.push({ input, error: `HTTP ${response.status}` });
    continue;
  }
  const data = await response.json();
  const filled = Object.entries(data.symptoms || {})
    .filter(([, v]) => v !== null && v !== undefined)
    .map(([k, v]) => `${k}=${v}`)
    .join(', ') || '(none)';
  rows.push({
    input,
    detected: data.language_detected,
    normalized: data.normalized_text,
    filled,
    triage: data.triage?.level ?? 'n/a',
    source: data.source,
    notice: data.fallback_notice ? 'yes' : 'no',
  });
}

const lines = [];
lines.push('# Failure-case evidence table');
lines.push('');
lines.push('Generated by `scripts/generate-evidence.sh`. The backend runs with');
lines.push('`--sakhi.llm.fail=true`, so every row below is a genuine LLM-failure');
lines.push('case: the request fell back to the offline keyword extractor and the');
lines.push('response carried the visible `fallback_notice`.');
lines.push('');
lines.push(`Generated: ${new Date().toISOString()}`);
lines.push('');
lines.push('| # | Language | Case | Input | Detected | Normalized text | Fields filled | Triage | Fallback notice |');
lines.push('|---|----------|------|-------|----------|-----------------|--------------|--------|-----------------|');
rows.forEach((row, i) => {
  const { input } = row;
  if (row.error) {
    lines.push(`| ${i + 1} | ${input.language} | ${esc(input.title)} | \`${esc(input.text)}\` | ERROR | ${esc(row.error)} | - | - | - |`);
    return;
  }
  lines.push(
    `| ${i + 1} | ${input.language} | ${esc(input.title)} | \`${esc(input.text)}\` `
    + `| ${row.detected} | ${esc(row.normalized)} | ${esc(row.filled)} `
    + `| ${row.triage} | ${row.notice} |`,
  );
});
lines.push('');
lines.push('## Expected behaviour per case');
lines.push('');
lines.push('| Case | Input id | Expected |');
lines.push('|------|----------|----------|');
for (const input of inputs) {
  lines.push(`| ${esc(input.title)} | ${input.id} | ${esc(input.expect)} |`);
}
lines.push('');
lines.push('## How to reproduce');
lines.push('');
lines.push('```bash');
lines.push('scripts/generate-evidence.sh   # starts the backend, regenerates this file, stops it');
lines.push('```');
lines.push('');

mkdirSync(dirname(resolve(outputPath)), { recursive: true });
writeFileSync(resolve(outputPath), lines.join('\n'), 'utf8');
console.log(`wrote ${outputPath} (${rows.length} rows, ${failures} failures)`);

if (failures > 0) process.exit(1);
