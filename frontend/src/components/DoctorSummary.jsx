import { CHIPS, formatChipValue } from '../lib/constants.js';

const QUESTIONS_TO_ASK = [
  'Could my irregular cycles be related to thyroid issues, pregnancy, anaemia or stress?',
  'Which tests do you recommend for me, and when should I retest?',
  'Do my bleeding or pain symptoms need urgent assessment?',
  'What lifestyle changes or medicines would help while we wait for results?',
];

const TESTS_COMMONLY_DISCUSSED = [
  { name: 'Ultrasound (pelvic)', why: 'Looks at the ovaries and the uterine lining.' },
  { name: 'Hormone panel', why: 'Checks testosterone, LH/FSH, prolactin and thyroid hormones.' },
  { name: 'Glucose (fasting)', why: 'Screens for insulin resistance and diabetes.' },
  { name: 'HbA1c', why: 'Shows the average blood sugar over the last 3 months.' },
];

function valueText(chip, entry) {
  if (!entry || entry.value === null || entry.value === undefined) return 'Not answered';
  return formatChipValue(chip, entry.value);
}

/**
 * Printable English summary for a doctor visit: confirmed symptoms, cycle
 * data, questions to ask and tests commonly discussed.
 * Printing shows only this section (see .print-summary in styles.css).
 */
export default function DoctorSummary({ answers, cycleStats, reportedText, ready }) {
  const stats = cycleStats;

  return (
    <section className="card print-summary" aria-labelledby="summary-title">
      <h2 id="summary-title">Doctor summary (printable, English)</h2>

      {!ready && (
        <p className="hint">
          Analyse your description first to fill in the assistant&apos;s answers;
          then confirm or correct the chips above.
        </p>
      )}

      <button
        type="button"
        className="print-button no-print"
        onClick={() => window.print()}
      >
        Print / Save as PDF
      </button>

      <div className="summary-body">
        <h3>1. Confirmed symptoms</h3>
        <table className="summary-table">
          <tbody>
            {CHIPS.map((chip) => (
              <tr key={chip.field}>
                <th scope="row">{chip.label}</th>
                <td>{valueText(chip, answers && answers[chip.field])}</td>
              </tr>
            ))}
          </tbody>
        </table>

        <h3>2. Cycle data</h3>
        <ul className="summary-list">
          <li>Cycle gap (days): {valueText(CHIPS[0], answers && answers.cycle_gap_days)}</li>
          <li>
            Period start dates selected: {stats && stats.count > 0 ? stats.dates.join(', ') : 'none'}
          </li>
          {stats && stats.ready ? (
            <>
              <li>Gaps between periods (days): {stats.gaps.join(', ')}</li>
              <li>Average gap: {stats.averageGapDays} days</li>
              <li>
                Pattern: {stats.verdict}
                {stats.irregular ? ` - ${stats.reasons.join('; ')}` : ''}
              </li>
            </>
          ) : (
            <li>Pattern: not enough dates selected in the calendar</li>
          )}
        </ul>

        <h3>3. What the patient reported</h3>
        <p className="summary-report">
          {reportedText && reportedText.trim()
            ? reportedText
            : '(no description entered)'}
        </p>

        <h3>4. Questions to ask the doctor</h3>
        <ol className="summary-list">
          {QUESTIONS_TO_ASK.map((q) => (
            <li key={q}>{q}</li>
          ))}
        </ol>

        <h3>5. Tests commonly discussed</h3>
        <ul className="summary-list">
          {TESTS_COMMONLY_DISCUSSED.map((t) => (
            <li key={t.name}>
              <strong>{t.name}</strong> - {t.why}
            </li>
          ))}
        </ul>

        <p className="summary-footer">
          Generated by Yajnaseni from patient-confirmed answers. This is
          information, not a diagnosis.
        </p>
      </div>
    </section>
  );
}
